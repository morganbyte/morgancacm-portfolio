"""Turn a photo into the ASCII portrait used on the home page.

    python3 scripts/ascii_portrait.py [photo] [cols]
    python3 scripts/ascii_portrait.py public/morgan.png 150

Writes app/data/portrait.ts. Needs Pillow (pip install pillow).

Works best with a plain, light background: everything bright that is connected
to the top/left/right edges is treated as background and dropped.
"""
import sys
from collections import deque
from pathlib import Path
from PIL import Image, ImageFilter, ImageOps

SRC = sys.argv[1] if len(sys.argv) > 1 else "public/morgan.png"
COLS = int(sys.argv[2]) if len(sys.argv) > 2 else 150
OUT = Path("app/data/portrait.ts")

# Dark → light. Dense glyphs read as bright on the dark site.
RAMP = " .:-=+*1i%$0#8@"
BG_THRESHOLD = 205  # 0–255: brighter than this and touching the edge = background
TOP_CROP = 0.10  # drop this fraction of empty space above the head
BOTTOM_CROP = 0.84  # keep down to here (the chest is a flat block of clothing)
FLOOR = 0.10  # minimum tone inside the figure, so black hair/clothes keep a silhouette
GAMMA = 1.5  # >1 deepens shadows (eyes, brows, beard)


def background_mask(gray: Image.Image) -> Image.Image:
    """255 = person, 0 = background."""
    W, H = gray.size
    small = gray.resize((W // 2, H // 2)).filter(ImageFilter.GaussianBlur(1.5))
    w, h = small.size
    p = small.load()
    bg = bytearray(w * h)
    q = deque([(x, 0) for x in range(w)] + [(0, y) for y in range(h)] + [(w - 1, y) for y in range(h)])
    while q:
        x, y = q.popleft()
        if not (0 <= x < w and 0 <= y < h) or bg[y * w + x] or p[x, y] < BG_THRESHOLD:
            continue
        bg[y * w + x] = 1
        q.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    m = Image.frombytes("L", (w, h), bytes(0 if b else 255 for b in bg))
    m = m.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MaxFilter(3))
    m = m.filter(ImageFilter.MinFilter(5))  # pull the edge in: avoids a bright halo from the background
    return m.filter(ImageFilter.GaussianBlur(1)).resize((W, H))


def main() -> None:
    gray = Image.open(SRC).convert("L")
    mask = background_mask(gray)

    W, H = gray.size
    box = (0, int(H * TOP_CROP), W, int(H * BOTTOM_CROP))
    gray, mask = gray.crop(box), mask.crop(box)

    gray = ImageOps.autocontrast(gray, cutoff=0.5)
    gray = gray.filter(ImageFilter.UnsharpMask(radius=4, percent=140, threshold=2))

    w, h = gray.size
    rows = int(COLS * h / w * 0.5)  # monospace cells are ~2× taller than wide
    gray = gray.resize((COLS, rows), Image.LANCZOS)
    mask = mask.resize((COLS, rows), Image.LANCZOS)

    # Stretch only the person's tones (the white background would skew it).
    px, mk = gray.load(), mask.load()
    vals = sorted(px[x, y] for y in range(rows) for x in range(COLS) if mk[x, y] > 128)
    lo, hi = vals[int(len(vals) * 0.02)], vals[int(len(vals) * 0.995)]

    lines = []
    for y in range(rows):
        line = ""
        for x in range(COLS):
            if mk[x, y] < 128:
                line += " "
                continue
            v = min(1.0, max(0.0, (px[x, y] - lo) / (hi - lo))) ** GAMMA
            v = FLOOR + (1 - FLOOR) * v
            line += RAMP[min(len(RAMP) - 1, 1 + int(v * (len(RAMP) - 1)))]
        lines.append(line.rstrip())

    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    width = max(len(l) for l in lines)
    lines = [l.ljust(width) for l in lines]

    body = "\n".join(lines).replace("\\", "\\\\").replace("`", "\\`").replace("$", "\\$")
    ramp = RAMP.replace("\\", "\\\\").replace('"', '\\"')
    OUT.write_text(
        "// Generated by scripts/ascii_portrait.py — do not edit by hand.\n"
        f"export const portraitCols = {width};\n"
        f"export const portraitRows = {len(lines)};\n"
        f'export const portraitRamp = "{ramp}";\n'
        f"export const portrait = `{body}`;\n"
    )
    print(f"{OUT}: {width}×{len(lines)}")


if __name__ == "__main__":
    main()
